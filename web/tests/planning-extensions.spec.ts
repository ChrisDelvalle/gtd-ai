import {fixtureContent} from "./helpers/content";
import { test, expect } from "@playwright/test";

for (const width of [390, 1280]) test(`estimates, availability, buffer and multiple blocks at ${width}`, async ({page,request,baseURL}, info) => {
  await page.setViewportSize({width,height:900});
  await page.emulateMedia({colorScheme:width===390?"dark":"light",reducedMotion:"reduce"});
  const headers={Origin:baseURL!,"X-GTD-Request":"1"};
  const call=async(name:string,args:object)=>{
    const r=await request.post(`/api/tools/${name}`,{headers,data:fixtureContent(name,args)});
    expect(r.ok()).toBeTruthy();return r.json();
  };
  const {task}=await call("capture_item",{title:`Plan sessions ${crypto.randomUUID()}`,status:"next",importance:"high",estimated_minutes:60,effort:"high",reason:"Disposable fixture",request_id:crypto.randomUUID()});
  await page.route("**/api/tools/list_items",route=>route.continue({postData:JSON.stringify({...route.request().postDataJSON(),task_id:task.id})}));
  await page.goto(`/tasks/${task.id}`);
  await page.getByRole("button",{name:`More options: ${task.title}`,exact:true}).click();
  await page.getByRole("menuitem",{name:"Edit",exact:true}).click();
  const e=page.getByRole("region",{name:"Task details",exact:true});
  await e.getByLabel("Remaining minutes",{exact:true}).fill("75");
  await e.getByLabel("Effort",{exact:true}).selectOption("medium");
  await e.getByLabel("Deadline",{exact:true}).fill("2090-01-10");
  await e.getByRole("button",{name:"Timing",exact:true}).click();
  await e.getByLabel("Not before",{exact:true}).fill("2090-01-02");
  await e.getByLabel("Buffer",{exact:true}).fill("2");
  await e.getByRole("button",{name:"Add block",exact:true}).click();
  await e.getByLabel("Planned start",{exact:true}).fill("2090-01-01");
  await expect(e.getByText("This block begins before availability.",{exact:true})).toBeVisible();
  await e.getByLabel("Planned start",{exact:true}).fill("2090-01-03");
  await e.getByRole("button",{name:"Add block",exact:true}).click();
  await e.getByLabel("Block 2 start",{exact:true}).fill("2090-01-05");
  await e.getByLabel("Block 2 finish",{exact:true}).fill("2090-01-06");
  await e.getByLabel("Block 2 calendar event",{exact:true}).fill("https://calendar.google.com/calendar/event?eid=fixture");
  const overflow=await e.locator("input,select").evaluateAll(nodes=>nodes.some(n=>{const r=n.getBoundingClientRect();return r.width>0&&(r.left<0||r.right>innerWidth+1);}));
  expect(overflow).toBe(false);
  await page.screenshot({path:info.outputPath("multiple-blocks.png")});
  await e.getByRole("button",{name:"Save changes",exact:true}).click();
  await expect(e.getByText("All changes saved",{exact:true})).toBeVisible();
  const saved=(await call("list_items",{task_id:task.id})).items[0];
  expect(saved.estimated_minutes).toBe(75);expect(saved.effort).toBe("medium");
  expect(saved.status).toBe("blocked");expect(saved.manual_block).toBe(false);
  expect(saved.blocking_reasons.map((r:any)=>r.kind)).toContain("availability");
  expect(saved.buffer_target.date).toBe("2090-01-08");expect(saved.work_blocks).toHaveLength(2);
  expect(saved.work_blocks[1].calendar_event.url).toContain("eid=fixture");
  await e.getByRole("button",{name:"Remove block 1",exact:true}).click();
  await e.getByRole("button",{name:"Save changes",exact:true}).click();
  await expect(e.getByText("All changes saved",{exact:true})).toBeVisible();
  const remaining=(await call("list_items",{task_id:task.id})).items[0];
  expect(remaining.work_blocks.map((b:any)=>b.id)).toEqual([saved.work_blocks[1].id]);
  expect(remaining.planned_start).toBeNull();
});
