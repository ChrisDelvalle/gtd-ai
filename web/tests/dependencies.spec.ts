for (const width of [390,1280]) test(`website dependency edits and manual holds at ${width}`,async({page,request,baseURL},info)=>{
 await page.setViewportSize({width,height:900}); await page.emulateMedia({colorScheme:width===390?"dark":"light",reducedMotion:"reduce"});
 const call=async(name:string,args:object)=>{const r=await request.post(`/api/tools/${name}`,{headers:{Origin:baseURL!,"X-GTD-Request":"1"},data:fixtureContent(name,args)});expect(r.ok()).toBeTruthy();return r.json();};
 const suffix=crypto.randomUUID().slice(0,8);
 const make=(title:string,blocked_by:string[]=[])=>call("capture_item",{request_id:crypto.randomUUID(),title,importance:"high", estimated_minutes: 30, effort: "medium",status:"next",blocked_by,reason:"Disposable dependency UI fixture"});
 const a=(await make(`Choose the target ${suffix}`)).task;
 const title=`Submit the application ${suffix}`;
 const b=(await make(title,[a.id])).task;
 await page.goto("/");
 if(width<1041)await page.getByRole("button",{name:"Open navigation",exact:true}).click();
 await page.getByRole("navigation",{name:"Task views"}).getByRole("button",{name:"Blocked",exact:true}).click();
 await page.getByRole("button",{name:`More options: ${title}`,exact:true}).click();
 await page.getByRole("menuitem",{name:"Edit",exact:true}).click();
 const e=page.getByRole("region",{name:"Task details",exact:true});
 await expect(e.getByRole("combobox",{name:"Status",exact:true})).toHaveValue("blocked");
 await expect(e.getByLabel("Keep blocked manually")).not.toBeChecked();
 await expect(e.locator(".dependency-selection")).toContainText(a.title);
 await e.getByLabel("Notes",{exact:true}).fill("Prepare the application after choosing the target.");
 const write=page.waitForResponse(r=>r.url().endsWith("/api/tools/update_item")&&r.request().method()==="POST");
 await e.getByRole("button",{name:"Save changes",exact:true}).click();
 const saved=await(await write).json();expect(saved.task.status).toBe("blocked");expect(saved.task.manual_block || false).toBe(false);
 await expect(e.getByText("All changes saved",{exact:true})).toBeAttached();
 await e.getByLabel("Keep blocked manually").check();
 await e.getByLabel("Keep blocked manually").scrollIntoViewIfNeeded();
 await page.screenshot({path:info.outputPath("dependency-editor.png")});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 const write2=page.waitForResponse(r=>r.url().endsWith("/api/tools/update_item")&&r.request().method()==="POST");
 await e.getByRole("button",{name:"Save changes",exact:true}).click();expect((await(await write2).json()).task.manual_block).toBe(true);
 await call("update_item",{request_id:crypto.randomUUID(),task_id:a.id,expected_version:a.version,status:"done",reason:"Complete prerequisite"});
 const held=(await call("list_items",{task_id:b.id})).items[0];expect(held.status).toBe("blocked");
 await e.getByLabel("Keep blocked manually").uncheck();
 const write3=page.waitForResponse(r=>r.url().endsWith("/api/tools/update_item")&&r.request().method()==="POST");await e.getByRole("button",{name:"Save changes",exact:true}).click();expect((await(await write3).json()).task.status).toBe("next");
});
